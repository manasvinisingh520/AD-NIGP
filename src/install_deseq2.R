userlib <- file.path(Sys.getenv("USERPROFILE"), "Rlibs")
dir.create(userlib, showWarnings = FALSE, recursive = TRUE)
.libPaths(c(userlib, .libPaths()))
options(repos = c(CRAN = "https://cloud.r-project.org"))
cat("Installing into:", userlib, "\n")
if (!requireNamespace("BiocManager", quietly = TRUE)) install.packages("BiocManager", lib = userlib)
BiocManager::install(c("DESeq2", "stageR"), update = FALSE, ask = FALSE, lib = userlib)
cat("DESeq2 installed:", requireNamespace("DESeq2", quietly = TRUE), "\n")
cat("stageR installed:", requireNamespace("stageR", quietly = TRUE), "\n")
